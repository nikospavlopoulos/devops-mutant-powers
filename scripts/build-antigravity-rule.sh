#!/usr/bin/env bash
# Generate rules/devops-mutant-powers.md: the Antigravity always-on plugin rule that bootstraps the plugin.
# Antigravity activates plugin rules automatically; its SessionStart hook output is undocumented, so rules are used.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BOOT="$ROOT/skills/using-devops-mutant-powers"
OUT="${1:-$ROOT/rules/devops-mutant-powers.md}"
version=$(jq -r .version "$ROOT/.claude-plugin/plugin.json")
strip_frontmatter() { awk 'NR==1 && /^---$/ {f=1; next} f && /^---$/ {f=0; next} !f' "$1"; }

mkdir -p "$(dirname "$OUT")"
{
  printf -- '---\ntrigger: always_on\ndescription: Bootstrap for the devops-mutant-powers plugin. GENERATED by scripts/build-antigravity-rule.sh, do not edit.\n---\n\n'
  printf '<EXTREMELY_IMPORTANT>\nYou have devops-mutant-powers v%s.\n\n' "$version"
  printf 'Its skills are installed under this plugin'"'"'s skills/ directory. Antigravity has no Skill tool: when a skill applies, read its SKILL.md with the file-read tool and follow it.\n\n'
  strip_frontmatter "$BOOT/SKILL.md"
  printf '\n\n'
  cat "$BOOT/references/antigravity-tools.md"
  printf '\n</EXTREMELY_IMPORTANT>\n'
} > "$OUT"
