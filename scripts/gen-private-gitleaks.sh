#!/usr/bin/env bash
# Generate the private gitleaks config (repo rules + private denylist rule). Output stays outside the repo.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONF_DIR="${NSD_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/devops-mutant-powers}"
DENYLIST="${NSD_DENYLIST:-$CONF_DIR/denylist.txt}"
OUT="${NSD_PRIVATE_GITLEAKS:-$CONF_DIR/gitleaks-private.toml}"

if [ ! -s "$DENYLIST" ]; then
  echo "scan: private denylist missing or empty: $DENYLIST" >&2
  echo "scan: create it (one internal term per line, mode 600)" >&2
  exit 2
fi

# Escape regex metacharacters, longest terms first so alternation prefers specific matches.
terms=$(grep -vE '^[[:space:]]*(#|$)' "$DENYLIST" \
  | sed -e 's/[[:space:]]*$//' -e 's/[.^$*+?()[{}|\\]/\\&/g' -e 's/\]/\\]/g' \
  | awk '{ print length, $0 }' | sort -rn | cut -d' ' -f2- | paste -sd'|' -) || true
if [ -z "$terms" ]; then
  echo "scan: private denylist has no terms (only comments/blank lines): $DENYLIST" >&2
  exit 2
fi

# Lines carrying this repo's own URL, SSH alias or Host/HostName block are allowed by the denylist rule (path scope is
# enforced by scan-sensitive.sh). Identity comes from package.json + origin, so alias, HTTPS and local clones agree.
esc() { printf '%s' "$1" | sed -e 's/[.^$*+?()[{}|\\]/\\&/g'; }
url_regexes=""
ident=$(python3 -I "$ROOT/scripts/lib/check_hostnames.py" "$ROOT" --identity) || { echo "scan: cannot derive repo identity" >&2; exit 2; }
while IFS=$'\t' read -r kind val; do
  [ -n "$val" ] || continue
  e=$(esc "$val")
  case "$kind" in
    path)  url_regexes="$url_regexes
  '''[A-Za-z0-9.@-]+[/:]${e}(\\.git)?''',";;
    host)  url_regexes="$url_regexes
  '''^\\s*HostName\\s+${e}\\s*$''',";;
    alias) url_regexes="$url_regexes
  '''^\\s*Host\\s+${e}\\s*$''',";;
  esac
done < <(printf '%s' "$ident" | python3 -I -c 'import json,sys
d=json.load(sys.stdin)
for k,key in (("path","paths"),("host","hosts"),("alias","aliases")):
    for v in d[key]: print(k+"\t"+v)')

umask 077
mkdir -p "$(dirname "$OUT")"
cat > "$OUT" <<EOF
# GENERATED by scripts/gen-private-gitleaks.sh from the private denylist. NEVER commit.
title = "devops-mutant-powers (private)"

[extend]
path = "$ROOT/.gitleaks.toml"

[[rules]]
id = "private-denylist"
description = "Internal name, host, domain or IP from the private denylist"
regex = '''(?i)\\b(${terms})\\b'''
tags = ["private"]

    [rules.allowlist]
    regexTarget = "line"
    regexes = [
${url_regexes}
    ]
EOF
echo "$OUT"
